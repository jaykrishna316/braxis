class TestIntegrationAcrossExtractors(unittest.TestCase):
    """Integration tests using real documentation examples"""

    def test_morluto_rea_extraction(self):
        """Test extraction on morluto/rea documentation"""
        content = """
        # REA - Reverse Engineering Analysis

        REA is a local-only reverse-engineering tool.

        ## Product and Authority
        Ghidra uses ephemeral databases without modifying executable bytes.
        IDA analysis is read-only; never save or close an attached GUI database.

        Configuration changes must be additive and idempotent.
        REA must not install or upgrade unrelated software.

        ## Architecture
        Dependencies flow inward: domain → adapters → workflows → CLI.
        Never commit binaries or provider documents.
        """
        # Test with all extractors
        auth = ProductAuthorityExtractor().extract(content)
        constraints = ArchitecturalConstraintsExtractor().extract(content)

        self.assertTrue(auth["found"])
        self.assertTrue(constraints["found"])

    def test_anthropic_sdk_extraction(self):
        """Test extraction on anthropic-sdk-python documentation"""
        content = """
        # anthropic-sdk-python

        ## File Ownership
        Hand-written: src/anthropic/lib/
        Generated: Everything else (with Stainless trailers)

        Stainless-Generated-From: ...

        ## Sync/Async Twins
        Keep Anthropic and AsyncAnthropic in sync.
        Fix one, fix the other.

        Do not make breaking changes to public APIs.
        """
        code_gen = CodeGenerationExtractor().extract(content)
        multi = MultiVariantExtractor().extract(content)
        constraints = ArchitecturalConstraintsExtractor().extract(content)

        self.assertTrue(code_gen["found"])
        self.assertTrue(multi["found"] or len(multi["twins"]) > 0)
        self.assertTrue(constraints["found"])


