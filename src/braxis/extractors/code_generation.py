"""Feature 3: Code Generation Pattern Detection

Detects auto-generated files, provider patterns (Stainless, OpenAPI),
trailers, and safe merge strategies.
"""

import re
from typing import Dict, List, Optional


class CodeGenerationExtractor:
    """Extract code generation patterns and ownership."""

    # Provider signatures
    PROVIDER_PATTERNS = {
        "stainless": (r"stainless|Stainless-Generated-From", "Stainless"),
        "openapi": (r"openapi|swagger", "OpenAPI"),
        "protobuf": (r"protobuf|grpc", "Protobuf"),
        "thrift": (r"thrift", "Thrift"),
        "graphql": (r"graphql|graphql-codegen", "GraphQL"),
        "typescript": (r"typescript|ts-codegen", "TypeScript Codegen"),
    }

    # Generated file patterns
    GENERATED_PATTERNS = [
        r"generated",
        r"auto.generated",
        r"autogenerated",
        r"do not edit",
        r"do not modify",
        r"THIS FILE IS GENERATED",
        r"Auto-generated",
    ]

    # Trailer patterns in commits/files
    TRAILER_PATTERNS = [
        r"Stainless-Generated-From",
        r"Generated-From",
        r"Co-Authored-By.*<generated",
    ]

    def __init__(self):
        """Initialize extractor."""
        self.provider_patterns = {
            name: re.compile(pattern, re.IGNORECASE)
            for name, (pattern, _) in self.PROVIDER_PATTERNS.items()
        }
        self.generated_patterns = [re.compile(p, re.IGNORECASE) for p in self.GENERATED_PATTERNS]
        self.trailer_patterns = [re.compile(p, re.IGNORECASE) for p in self.TRAILER_PATTERNS]

    def extract(self, content: str, file_path: str = "") -> Dict[str, any]:
        """Extract code generation patterns from documentation."""
        if not content:
            return {
                "found": False,
                "providers": {},
                "generated_files": [],
                "ownership_map": {},
                "merge_strategies": {},
            }

        result = {
            "found": False,
            "providers": self._detect_providers(content),
            "generated_files": self._detect_generated_files(content),
            "ownership_map": self._build_ownership_map(content),
            "merge_strategies": self._extract_merge_strategies(content),
            "trailers": self._detect_trailers(content),
        }

        result["found"] = bool(
            result["providers"] or result["generated_files"] or result["trailers"]
        )

        return result

    def _detect_providers(self, content: str) -> Dict[str, str]:
        """Detect code generation providers."""
        providers = {}

        for name, pattern in self.provider_patterns.items():
            if pattern.search(content):
                providers[name] = self.PROVIDER_PATTERNS[name][1]

        return providers

    def _detect_generated_files(self, content: str) -> List[Dict[str, str]]:
        """Detect generated file patterns."""
        files = []
        lines = content.split("\n")

        for i, line in enumerate(lines):
            for pattern in self.generated_patterns:
                if pattern.search(line):
                    # Extract context
                    section = self._extract_file_context(lines, i)
                    if section:
                        files.append(section)
                    break

        return files

    def _extract_file_context(self, lines: List[str], idx: int) -> Optional[Dict[str, str]]:
        """Extract file/ownership context around line."""
        start = max(0, idx - 1)
        end = min(len(lines), idx + 3)

        context = "\n".join(lines[start:end]).strip()

        # Try to extract file pattern
        file_match = re.search(r"([a-zA-Z_\-\.]+\.py|[a-zA-Z_\-\.]+\.js|[a-zA-Z_\-\.]+\.ts)", context)
        filename = file_match.group(1) if file_match else "unknown"

        return {
            "filename": filename,
            "context": context,
            "auto_generated": True,
        }

    def _build_ownership_map(self, content: str) -> Dict[str, str]:
        """Build map of who owns which files."""
        ownership = {}
        lines = content.split("\n")

        for i, line in enumerate(lines):
            # Look for ownership patterns
            if "hand-written" in line.lower() or "hand written" in line.lower():
                file_match = re.search(r"([a-zA-Z_\-\./]+\.py|[a-zA-Z_\-\./]+\.js)", line)
                if file_match:
                    ownership[file_match.group(1)] = "hand_written"

            if "generated" in line.lower() and "do not edit" not in line.lower():
                file_match = re.search(r"([a-zA-Z_\-\./]+\.py|[a-zA-Z_\-\./]+\.js)", line)
                if file_match:
                    ownership[file_match.group(1)] = "generated"

        return ownership

    def _extract_merge_strategies(self, content: str) -> Dict[str, str]:
        """Extract merge strategy guidance."""
        strategies = {}

        if "merge conflict" in content.lower():
            if "stainless" in content.lower():
                strategies["stainless"] = "Keep local changes, fix in generator, merge when generator merges"
            else:
                strategies["generated"] = "Resolve in upstream generator first, then merge"

        if "fix.*generator" in content.lower() or "fix.*upstream" in content.lower():
            strategies["default"] = "Fix in generator/upstream, never in generated files"

        return strategies

    def _detect_trailers(self, content: str) -> List[str]:
        """Detect code generation trailers in commits/files."""
        trailers = []

        for pattern in self.trailer_patterns:
            matches = pattern.findall(content)
            trailers.extend(matches)

        return list(set(trailers))  # Unique


def format_code_generation_section(extraction: Dict[str, any]) -> str:
    """Format code generation extraction as AGENTS.md section."""
    if not extraction["found"]:
        return ""

    lines = ["## 🔧 Code Generation & File Ownership\n"]

    if extraction["providers"]:
        lines.append("### Detected Providers\n")
        for provider, name in extraction["providers"].items():
            lines.append(f"• {name} ({provider})\n")

    if extraction["generated_files"]:
        lines.append("### Generated Files\n")
        lines.append("The following files are auto-generated. Fix issues in the generator, not here:\n")
        for file_info in extraction["generated_files"][:10]:
            lines.append(f"• `{file_info['filename']}`\n")

    if extraction["ownership_map"]:
        lines.append("### Ownership Map\n")
        for filepath, owner in extraction["ownership_map"].items():
            owner_label = "✅ Hand-written (safe to edit)" if owner == "hand_written" else "⚠️ Generated (fix upstream)"
            lines.append(f"• `{filepath}` — {owner_label}\n")

    if extraction["merge_strategies"]:
        lines.append("### Merge Strategies\n")
        for strategy_type, guidance in extraction["merge_strategies"].items():
            lines.append(f"**{strategy_type.title()}**: {guidance}\n")

    return "\n".join(lines)
